// Regenerates e2e/fixtures/dictionary.sql from a local D1 database that holds real published
// entries: node e2e/fixtures/export.mjs <path to the D1 .sqlite file>
//
// The fixture is a closed slice of the dictionary for the public-site journeys: the nodes, facts,
// worklist rows, and built public view rows of a few related entries, with their reference data.
// Each worklist row's view revision is its revision, so reads serve the exported views as built.
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { DatabaseSync } from 'node:sqlite'
import { fileURLToPath } from 'node:url'

const LEMMAS = [
  'animal', 'bird', 'fish', 'pet', 'creature', 'dog', 'cat', 'canine', 'mammal', 'eagle', 'owl',
  'sparrow', 'wing', 'beak', 'feather', 'hot', 'cold',
]

const source = process.argv[2]
if (!source) throw new Error('Pass the path of the D1 .sqlite file to export from.')
const db = new DatabaseSync(source, { readOnly: true })
const rows = (sql, ...params) => db.prepare(sql).all(...params)
const list = (values) => values.map(() => '?').join(', ')

const entries = rows(`select * from entries where lemma in (${list(LEMMAS)}) order by lemma`, ...LEMMAS)
const missing = LEMMAS.filter((lemma) => !entries.some((entry) => entry.lemma === lemma))
if (missing.length > 0) throw new Error(`No entry for: ${missing.join(', ')}`)
const entryIds = entries.map((entry) => entry.id)
const senses = rows(`select * from senses where entry_id in (${list(entryIds)}) order by id`, ...entryIds)
const nodeIds = [...entryIds, ...senses.map((sense) => sense.id)]
const nodes = new Set(nodeIds)
const facts = rows(`select * from facts where subject_id in (${list(nodeIds)}) order by id`, ...nodeIds).filter(
  (fact) => fact.object_id === null || nodes.has(fact.object_id),
)
const byEntry = (table) => rows(`select * from ${table} where entry_id in (${list(entryIds)})`, ...entryIds)
const worklist = byEntry('worklist').map((row) => ({ ...row, view_revision: row.revision }))
const words = entries.map((entry) => entry.lemma.toLowerCase())

const tables = [
  ['reference_sources', rows('select * from reference_sources order by id')],
  ['word_frequency', rows(`select * from word_frequency where word in (${list(words)})`, ...words)],
  ['lemma_cefr', rows(`select * from lemma_cefr where lemma in (${list(LEMMAS)})`, ...LEMMAS)],
  ['entries', entries],
  ['senses', senses],
  ['facts', facts],
  ['worklist', worklist],
  ['public_entries', byEntry('public_entries')],
  ['public_meanings', byEntry('public_meanings')],
  ['public_forms', byEntry('public_forms')],
  ['public_hypernyms', byEntry('public_hypernyms')],
  ['public_sense_topics', byEntry('public_sense_topics')],
  ['public_morphemes', byEntry('public_morphemes')],
  ['public_phrase_words', byEntry('public_phrase_words')],
  ['public_search', byEntry('public_search')],
]

const literal = (value) => {
  if (value === null || value === undefined) return 'NULL'
  if (typeof value === 'number' || typeof value === 'bigint') return String(value)
  return `'${String(value).replaceAll("'", "''")}'`
}
const statements = tables.flatMap(([table, items]) =>
  items.map((row) => {
    const columns = Object.keys(row)
    return `INSERT OR IGNORE INTO ${table} (${columns.map((c) => `"${c}"`).join(', ')}) VALUES (${columns.map((c) => literal(row[c])).join(', ')});`
  }),
)
const target = path.join(path.dirname(fileURLToPath(import.meta.url)), 'dictionary.sql')
writeFileSync(
  target,
  `-- Generated by e2e/fixtures/export.mjs; do not edit. Entries: ${LEMMAS.join(', ')}.\n${statements.join('\n')}\n`,
)
console.info(`${target}: ${tables.map(([table, items]) => `${table} ${items.length}`).join(', ')}`)
